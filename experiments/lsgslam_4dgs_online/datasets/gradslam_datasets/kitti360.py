import glob
import os
from pathlib import Path
from typing import Dict, List, Optional, Union

import numpy as np
import torch
from natsort import natsorted

from .kitti import KittiDataset


class Kitti360Dataset(KittiDataset):
    """
    KITTI-360 dataset loader.
    Inherits from KittiDataset so isinstance(dataset, KittiDataset) returns True,
    preserving all KITTI-specific logic in the SLAM pipeline.

    Expected directory layout (after preprocessing):
        {basedir}/{sequence}/
            image_00/data_rect/*.png    (left rectified images)
            depth_sceneflow/*.npy       (generated by operate_kitti360_data.py)
            global_features/*.npy       (generated by operate_kitti360_data.py)
            traj.txt                    (KITTI-format poses, only for frames with valid poses)
    """

    def get_filepaths(self):
        depth_paths = natsorted(glob.glob(f"{self.input_folder}/depth_sceneflow/*.npy"))
        frame_ids = [os.path.splitext(os.path.basename(p))[0] for p in depth_paths]

        color_paths = [
            os.path.join(self.input_folder, "image_00", "data_rect", f"{fid}.png")
            for fid in frame_ids
        ]
        feature_paths = natsorted(glob.glob(f"{self.input_folder}/global_features/*.npy"))

        embedding_paths = None
        if self.load_embeddings:
            embedding_paths = natsorted(glob.glob(f"{self.input_folder}/{self.embedding_dir}/*.pt"))

        return color_paths, depth_paths, embedding_paths, feature_paths
